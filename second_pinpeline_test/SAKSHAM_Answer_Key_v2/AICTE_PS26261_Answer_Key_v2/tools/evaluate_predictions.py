#!/usr/bin/env python3
"""Compare post-run model/API predictions with the separate answer key."""
import argparse,csv,json
from pathlib import Path
FIELDS=['expected_extraction_status','expected_source_verification_status','expected_anomaly_label','expected_infrastructure_status','expected_workflow_decision']
ALIASES={f:f.replace('expected_','predicted_') for f in FIELDS}
def load_csv(p):
    with open(p,encoding='utf-8-sig',newline='') as f: return list(csv.DictReader(f))
def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--predictions',required=True,help='CSV generated by the system under test; columns case_id,predicted_*')
    ap.add_argument('--answers',default='answer_key/expected_outcomes.csv')
    ap.add_argument('--out',default='evaluation_results.json')
    a=ap.parse_args(); preds=load_csv(a.predictions); ans=load_csv(a.answers)
    pmap={x['case_id']:x for x in preds}; amap={x['case_id']:x for x in ans}
    dup=[]
    if len(pmap)!=len(preds): dup.append('duplicate_prediction_case_ids')
    missing=sorted(set(amap)-set(pmap)); extra=sorted(set(pmap)-set(amap))
    metrics={}; rows=[]
    for field in FIELDS:
        predfield=ALIASES[field]; compared=0; correct=0
        for cid,ex in amap.items():
            if cid not in pmap: continue
            pv=(pmap[cid].get(predfield) or '').strip(); ev=(ex.get(field) or '').strip()
            if pv and ev:
                compared+=1; correct+=int(pv==ev)
        metrics[field]={'compared':compared,'correct':correct,'accuracy':(correct/compared if compared else None)}
    for cid in sorted(set(amap)|set(pmap)):
        row={'case_id':cid,'present_in_answers':cid in amap,'present_in_predictions':cid in pmap,'field_mismatches':[]}
        if cid in amap and cid in pmap:
            for field in FIELDS:
                pf=ALIASES[field]; ev=(amap[cid].get(field) or '').strip(); pv=(pmap[cid].get(pf) or '').strip()
                if pv != ev: row['field_mismatches'].append({'field':field,'expected':ev,'predicted':pv})
        rows.append(row)
    result={'predictions_file':str(Path(a.predictions)),'answers_file':str(Path(a.answers)),'expected_cases':len(amap),'prediction_rows':len(preds),'unique_prediction_case_ids':len(pmap),'missing_case_ids':missing,'unexpected_case_ids':extra,'duplicate_prediction_case_ids':dup,'field_metrics':metrics,'case_results':rows,'warning':'Synthetic benchmark only; scores measure agreement with supplied test expectations, not real-world regulatory accuracy.'}
    Path(a.out).write_text(json.dumps(result,indent=2,ensure_ascii=False)+'\n',encoding='utf-8')
    print(json.dumps({k:v for k,v in result.items() if k!='case_results'},indent=2,ensure_ascii=False))
    return 1 if missing or extra or dup or any(r.get('field_mismatches') for r in rows) else 0
if __name__=='__main__': raise SystemExit(main())
